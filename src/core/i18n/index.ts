export type LanguageKey = 'ar' | 'en';
export type TranslationKey = keyof typeof STRINGS.ar;

let currentLanguage: LanguageKey = 'ar';

// ---------------- Reactivity ----------------
let languageVersion = 0;
const listeners = new Set<() => void>();

function notifyLanguageChange() {
  languageVersion++;
  listeners.forEach((l) => {
    try {
      l();
    } catch (e) {}
  });
}

export function setLanguage(lang: LanguageKey) {
  if (lang === currentLanguage) return;
  currentLanguage = lang;
  notifyLanguageChange();
}

export function subscribeLanguage(listener: () => void): () => void {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

export function getLanguageVersion(): number {
  return languageVersion;
}

export function getCurrentLanguage(): LanguageKey {
  return currentLanguage;
}

export function isRTL(): boolean {
  return currentLanguage === 'ar';
}

/**
 * Reactive translation function with {placeholder} interpolation.
 */
export function t(key: TranslationKey | string, params?: Record<string, string | number>): string {
  const dict = STRINGS[currentLanguage] as Record<string, string>;
  const fallback = STRINGS.ar as Record<string, string>;
  let out = dict[key] || fallback[key] || String(key);
  if (params) {
    for (const k of Object.keys(params)) {
      out = out.replace(new RegExp(`\\{${k}\\}`, 'g'), String(params[k]));
    }
  }
  return out;
}

/**
 * Hook: re-renders the component when the app language changes.
 * Usage: const { t } = useT();
 */
export function useT() {
  useSyncExternalStore(subscribeLanguage, getLanguageVersion, getLanguageVersion);
  return { t, language: currentLanguage, isRTL: isRTL() };
}
